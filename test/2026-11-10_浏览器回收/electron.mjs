// Synthetic local pages only; exercise production NativeBrowser and its native views.
import { app, BaseWindow, WebContentsView } from 'electron';
import assert from 'node:assert/strict';
import { once } from 'node:events';
import http from 'node:http';
import fs from 'node:fs';
import os from 'node:os';
import path from 'node:path';

const temp = fs.mkdtempSync(path.join(os.tmpdir(), 'astrion-retention-'));
app.setPath('userData', path.join(temp, 'electron'));
app.whenReady().then(async () => {
const { NativeBrowser, setBrowserDataRoot } = await import('../../desktop-electron/src/browser/index.js');
const { handleBrowserRequest, setBrowserToken } = await import('../../desktop-electron/src/browser/ai/endpoint.js');
let decision = { release: [], deleted: [] };
let requested;
const server = http.createServer((request, response) => {
  if (request.url === '/api/browser-retention') {
    requested = JSON.parse(request.headers['x-astrion-browser-state']);
    response.setHeader('Content-Type', 'application/json');
    response.end(JSON.stringify({ success: true, username: 'host', ...decision }));
  } else response.end('<!doctype html><title>Retention fixture</title><button>Test</button>');
});
await new Promise(resolve => server.listen(0, '127.0.0.1', resolve));
const origin = `http://127.0.0.1:${server.address().port}`;
const window = new BaseWindow({ show: false, width: 1000, height: 700 });
const main = new WebContentsView();
window.contentView.addChildView(main);
await main.webContents.loadURL(origin);
setBrowserDataRoot(path.join(temp, 'data'));
const browser = new NativeBrowser(window, origin, null);
browser.retention.dispose();
browser.retention.requestPoll = () => {};
const host = browser.addViewHost(main);
const profile = browser.ensureProfile('host');
const scope = JSON.stringify(['agent', 'ws', 'conv_a']);
host.profile = profile; host.owner = `${profile.key}:${scope}`;
let checks = 0;
const check = (name, predicate) => { assert.ok(predicate, name); checks++; console.log(`PASS ${name}`); };
try {
  const first = browser.registry.create('about:blank');
  await first.view.webContents.loadURL(origin);
  const second = browser.registry.create('about:blank');
  await second.view.webContents.loadURL(origin);
  const oldView = first.view;
  const short = browser.ai.shortId(host.owner, first);
  const navigation = { tabs: [{ key: 'tab_a', kind: 'conv', conversation_kind: 'agent', workspace_id: 'ws', conversation_id: 'conv_a' }] };
  browser.retention.navigationChanged(navigation, { tabs: [] });
  decision = { release: [scope], deleted: [] };
  const contents = [first.view.webContents, second.view.webContents];
  const destroyed = Promise.all(contents.map(wc => once(wc, 'destroyed')));
  await browser.retention.poll();
  await destroyed;
  check('native poll sends owner scope and close intent', requested.owners.some(row => row.scope[2] === 'conv_a' && row.visit > 0 && row.closed));
  check('both webpages destroy their native webContents', contents.every(wc => wc.isDestroyed()) && first.suspended && second.suspended);
  check('suspension preserves URL, identity, tab order and selection', browser.tabs.has(first.id) && browser.snapshot(host).tabs[0].id === first.id && first.url === origin + '/' && host.active().id === second.id);
  browser.retention.navigationChanged({ tabs: [] }, navigation);
  await browser.command(host, { action: 'select', id: first.id });
  const resumed = browser.tabs.get(first.id);
  check('select recreates a distinct native view', !resumed.suspended && resumed.view !== oldView);
  check('short AI tab identity survives recreation', browser.ai.shortId(browser.main.owner, resumed) === short);
  const identity = { username: 'host', workspace_id: 'ws', conversation_id: 'conv_a' };
  const result = await browser.ai.call({ call_id: 'retention-check', op: 'snapshot', args: { tab_id: short }, identity, epoch: 0, any_site: true });
  check('AI can operate the recreated page', result.success && result.snapshot.text.includes('Test'));
  check('AI receives reload/state-loss notice', result.notes.some(note => note.includes('重新加载')));
  await browser.command(host, { action: 'select', id: second.id });
  profile.setFollowAi(false);
  browser.retention.suspend(resumed);
  const again = await browser.ai.call({ call_id: 'retention-again', op: 'snapshot', args: { tab_id: short }, identity, epoch: 0, any_site: true });
  check('AI restores only its target without changing user selection', again.success && browser.selected.get(host.owner) === second.id);
  check('restored AI snapshot resets the old baseline', again.snapshot.kind === 'full');
  const controller = new AbortController();
  controller.owner = host.owner;
  browser.ai.calls.set('in-flight', controller);
  setBrowserToken('fixture-token');
  const [, denied] = await handleBrowserRequest('/browser/release', {}, { identity });
  check('release requires the desktop bridge credential', !denied.success && !controller.signal.aborted);
  const [, forced] = await handleBrowserRequest('/browser/release', { 'x-astrion-browser-token': 'fixture-token' }, { identity });
  check('explicit release aborts browser calls and suspends the whole group', forced.success && controller.signal.aborted && [...browser.tabs.values()].every(tab => tab.suspended));
  check('suspended snapshot still offers both tabs', browser.snapshot(host).tabs.every(tab => tab.suspended));
  decision = { release: [], deleted: [scope] };
  await browser.retention.poll();
  check('deletion removes all owner tabs', browser.tabs.size === 0);
  check('deletion removes recovery and AI owner state', !profile.data.owners[host.owner] && !browser.ai.state.has(host.owner));
  console.log(`${checks} native retention checks passed`);
} finally {
  browser.dispose();
  main.webContents.close(); window.destroy();
  await new Promise(resolve => server.close(resolve));
  fs.rmSync(temp, { recursive: true, force: true });
  app.quit();
}
}).catch(error => { console.error(error); app.exit(1); });
