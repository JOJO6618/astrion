"""Resource protocols; importing these definitions creates no execution runtime."""
from __future__ import annotations

from typing import Any, Dict, List, Optional, Protocol


class TerminalBackend(Protocol):
    def open_terminal(self, session_name: str = "default", working_dir: Optional[str] = None,
                      make_active: bool = True) -> Dict[str, Any]: ...
    def close_terminal(self, session_name: str) -> Dict[str, Any]: ...
    def reset_terminal(self, session_name: Optional[str]) -> Dict[str, Any]: ...
    def list_terminals(self) -> Dict[str, Any]: ...
    def send_to_terminal(self, command: str, session_name: Optional[str] = None,
                         output_wait: float = 10) -> Dict[str, Any]: ...
    def get_terminal_snapshot(self, session_name: Optional[str] = None,
                              lines: Optional[int] = None,
                              max_chars: Optional[int] = None) -> Dict[str, Any]: ...
    def get_terminal_list(self) -> List[Dict[str, Any]]: ...
    def close_all(self) -> None: ...


class BackgroundBackend(Protocol):
    def get_record(self, command_id: str) -> Optional[Dict[str, Any]]: ...
    def get_record_with_output(self, command_id: str) -> Optional[Dict[str, Any]]: ...
    def list_records(self, *, conversation_id: Optional[str] = None,
                     limit: int = 200) -> List[Dict[str, Any]]: ...
    def wait_for_completion(self, command_id: str, timeout_seconds: Optional[float] = None,
                            claim: bool = False) -> Dict[str, Any]: ...
    def cancel_command(self, command_id: str) -> Dict[str, Any]: ...
    def poll_updates(self, conversation_id: Optional[str] = None) -> List[Dict[str, Any]]: ...
    def mark_notified(self, command_id: str) -> None: ...
    def unmark_notified(self, command_id: str) -> None: ...
    def mark_all_notified(self, conversation_id: Optional[str]) -> int: ...
    def mark_claimed(self, command_id: str) -> None: ...
    def has_pending_for_conversation(self, conversation_id: Optional[str]) -> bool: ...
    def list_waiting_items(self, conversation_id: Optional[str]) -> List[Dict[str, Any]]: ...
    def reconcile_stale_records(self, conversation_id: Optional[str] = None) -> int: ...
