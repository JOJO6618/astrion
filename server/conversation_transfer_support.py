"""Trusted material discovery, export expiry and desktop relocation helpers."""
from contextlib import nullcontext
from pathlib import Path
import re
import time

from modules.conversation_transfer.assets import collect, safe_file


def chat_materials(document, principal, data_dir):
    """Read completed handoffs only through the authenticated workspace catalog."""
    from server.chat_mode.handoff_workspace import identity_for, projects
    from server.context.workspace import resolve_workspace
    allowed = {row["id"] for row in projects(principal)}
    resources, files = [], {}
    for handoff in (document["metadata"].get("chat", {}).get("handoffs") or {}).values():
        relative = handoff.get("materials")
        workspace_id = handoff.get("workspace_id")
        if not relative:
            continue
        if workspace_id not in allowed:
            raise FileNotFoundError("A Chat handoff workspace is unavailable")
        if not isinstance(relative, str) or not re.fullmatch(r"\.astrion/handoff/[A-Za-z0-9_-]+", relative):
            raise ValueError("Invalid Chat handoff material directory")
        workspace = resolve_workspace(principal.username, workspace_id,
            identity=identity_for(principal, workspace_id), prepare=False)
        material_document = {"metadata": {}, "messages": [{"content": relative}]}
        rows, payloads = collect(material_document, data_dir, Path(workspace.project_path))
        resources.extend(rows)
        files.update(payloads)
    return resources, files


def export_path(data, manager, token):
    if data is not None:
        return safe_file(Path(data.workspace.project_path),
                         f".astrion/conversation_exports/{token}.astrion.zip")
    return safe_file(manager.base_dir, f"exports/{token}.astrion.zip")


def expire_exports(directory: Path):
    """Only delete expired exports with names generated by this application."""
    cutoff = time.time() - 24 * 60 * 60
    for path in directory.iterdir():
        if (re.fullmatch(r"[0-9a-f]{32}\.astrion\.zip", path.name)
                and not path.is_symlink() and path.is_file()
                and path.stat().st_mtime < cutoff):
            path.unlink(missing_ok=True)


def finish_migration(principal, data, manager, conversation_id, destination, label):
    from config import IS_HOST_MODE
    from modules.conversation_transfer.service import read_document, retire_source
    navigation = None
    if IS_HOST_MODE:
        from server.conversation_tabs import navigation
    # Reconcile cannot remove the original stable tab between retirement and
    # relocation. A complete destination already exists before entering here.
    with navigation.lock if navigation is not None else nullcontext():
        if navigation is not None:
            navigation.relocated(principal.username, data.workspace_id,
                destination["workspace_id"], conversation_id, label)
        if manager._get_conversation_file_path(conversation_id).exists():
            retire_source(manager, read_document(manager, conversation_id), destination)
        # Cached sources cannot keep executing the old in-memory history.
        # Disposal must not save it back after moving the file.
        from server import state
        from server.context.resources import _make_terminal_key, _resource_lock, _discard_runtime
        owner = "host" if getattr(data.workspace, "username", None) == "host" else principal.username
        key = _make_terminal_key(owner, data.workspace_id, conversation_id)
        with _resource_lock(key):
            terminal = state.user_terminals.get(key)
            if terminal is not None:
                terminal._reaper_closing = True
                context = terminal.context_manager
                context.auto_save_enabled = False
                context.current_conversation_id = None
                context.conversation_history = []
                context.todo_list = None
                _discard_runtime(terminal)
                if state.user_terminals.get(key) is terminal:
                    state.user_terminals.pop(key, None)
